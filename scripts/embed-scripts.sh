#!/bin/sh
# Generates Sources/LidAwakeCore/EmbeddedScripts.generated.swift from Resources/scripts/*.sh,
# so the app runs embedded text as root instead of a script file on disk.
set -eu
cd "$(dirname "$0")/.."
out="Sources/LidAwakeCore/EmbeddedScripts.generated.swift"
{
    echo "// Generated by scripts/embed-scripts.sh. Do not edit."
    echo "public enum EmbeddedScripts {"
    for pair in "grantAccess:grant-access.sh" "revokeAccess:revoke-access.sh"; do
        name="${pair%%:*}"
        file="Resources/scripts/${pair#*:}"
        printf '    public static let %s = #"""\n' "$name"
        cat "$file"
        printf '"""#\n'
    done
    echo "}"
} > "$out"
